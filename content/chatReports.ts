export const chatReportsCopy: Record<Locale, ChatReportsCopy> = { es, en };

/** Duración legible (segundos → s / min / h). */
export const fmtDuration = (locale: Locale, s: number | null | undefined) => {
  if (s == null) return "—";
  const d = chatReportsCopy[locale].reports.duration;
  if (s < 60) return d.s.replace("{n}", String(Math.round(s)));
  if (s < 3600) return d.m.replace("{n}", String(Math.round(s / 60)));
  return d.h.replace("{n}", (s / 3600).toFixed(1));
};
